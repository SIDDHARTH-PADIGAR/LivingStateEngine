# This project deliberately receives event 3 before event 2.
ARRIVAL_ORDER = {
    "late_arrival": [0, 2, 1, 3],
    "late_status_arrival": [0, 2, 1],
}


def write_jsonl(path: Path, rows: list[dict[str, Any]]) -> None:
    with path.open("w", encoding="utf-8", newline="\n") as handle:
        for row in rows:
            handle.write(
                json.dumps(
                    row,
                    sort_keys=True,
                    ensure_ascii=False,
                    allow_nan=False,
                ) + "\n"
            )


def read_jsonl(path: Path) -> list[dict[str, Any]]:
    with path.open("r", encoding="utf-8") as handle:
        return [json.loads(line) for line in handle if line.strip()]


def make_dataset() -> tuple[list[dict], list[dict], dict]:
    event_rows = []
    label_rows = []

    for scenario, steps in SCENARIOS.items():
        project_id = f"challenge-{scenario}"
        scenario_events = []

        for index, item in enumerate(steps, start=1):
            event_id = f"{project_id}-e{index:02d}"
            occurred_at = BASE_TIME + timedelta(
                days=item["day"],
                minutes=item["minute"],
            )

            scenario_events.append({
                "event_id": event_id,
                "project_id": project_id,
                "occurred_at": occurred_at.isoformat(),
                "event_type": item["event_type"],
                "summary": item["summary"],
                "source": "synthetic-challenge",
                "actor": "Synthetic project owner",
                "payload": item["payload"],
            })

            label_rows.append({
                "project_id": project_id,
                "scenario": scenario,
                "as_of_event_id": event_id,
                "occurred_at": occurred_at.isoformat(),
                "true_status": item["expected"],
            })

        order = ARRIVAL_ORDER.get(
            scenario, list(range(len(scenario_events)))
        )
        event_rows.extend(scenario_events[index] for index in order)

    manifest = {
        "synthetic": True,
        "benchmark_type": "hand-authored challenge benchmark",
        "scenario_count": len(SCENARIOS),
        "event_count": len(event_rows),
        "labeled_states": len(label_rows),
        "scenarios": list(SCENARIOS),
        "arrival_order_cases": list(ARRIVAL_ORDER),
        "label_source": (
            "Expected states are hand-authored in SCENARIOS and are "
            "not generated by StateEngine."
        ),
        "limitations": (
            "These are synthetic cases authored by the project developer, "
            "not independent real-world validation. They are intended to "
            "expose edge cases and should not be described as a production "
            "accuracy estimate."
        ),
    }

    return event_rows, label_rows, manifest


def baseline_predictions(events: list[Event]) -> dict[str, str]:
    status = "unknown"
    predictions = {}

    for event in sorted(
        events,
        key=lambda item: (item.occurred_at, item.event_id),
    ):
        if event.event_type in {"status_update", "project_update"}:
            raw = event.payload.get("status")
            if isinstance(raw, str):
                status = STATUS_MAP.get(raw.strip().lower(), status)

        predictions[event.event_id] = status

    return predictions


def score(truth: list[str], predictions: list[str]) -> dict[str, Any]:
    correct = sum(a == b for a, b in zip(truth, predictions))
    tp = sum(
        a in RISK_STATUSES and b in RISK_STATUSES
        for a, b in zip(truth, predictions)
    )
    fp = sum(
        a not in RISK_STATUSES and b in RISK_STATUSES
        for a, b in zip(truth, predictions)
    )
    fn = sum(
        a in RISK_STATUSES and b not in RISK_STATUSES
        for a, b in zip(truth, predictions)
    )
    tn = sum(
        a not in RISK_STATUSES and b not in RISK_STATUSES
        for a, b in zip(truth, predictions)
    )

    precision = tp / (tp + fp) if tp + fp else 0.0
    recall = tp / (tp + fn) if tp + fn else 0.0
    f1 = (
        2 * precision * recall / (precision + recall)
        if precision + recall else 0.0
    )

    return {
        "correct": correct,
        "total": len(truth),
        "accuracy": round(correct / len(truth), 4) if truth else 0.0,
        "risk_detection": {
            "true_positive": tp,
            "false_positive": fp,
            "false_negative": fn,
            "true_negative": tn,
            "precision": round(precision, 4),
            "recall": round(recall, 4),
            "f1": round(f1, 4),
        },
    }


def main() -> None:
    DATA_DIR.mkdir(parents=True, exist_ok=True)

    events_path = DATA_DIR / "challenge_events.jsonl"
    labels_path = DATA_DIR / "challenge_labels.jsonl"
    manifest_path = DATA_DIR / "challenge_manifest.json"
    results_path = DATA_DIR / "challenge_results.json"

    generated_events, generated_labels, manifest = make_dataset()
    write_jsonl(events_path, generated_events)
    write_jsonl(labels_path, generated_labels)
    manifest_path.write_text(
        json.dumps(manifest, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )

    # Ingest events in arrival order through the actual SQLite event store.
    with SQLiteEventStore(":memory:") as store:
        for row in read_jsonl(events_path):
            store.ingest_event(Event.from_dict(row))

        event_engine_predictions = {}
        event_baseline_predictions = {}

        engine = StateEngine()

        for project_id in store.list_projects():
            project_events = store.list_events(project_id)

            for version in engine.replay(project_events):
                event_engine_predictions[
                    (project_id, version.as_of_event_id)
                ] = version.status

            for event_id, status in baseline_predictions(
                project_events
            ).items():
                event_baseline_predictions[
                    (project_id, event_id)
                ] = status

    labels = read_jsonl(labels_path)
    truth_by_key = {
        (row["project_id"], row["as_of_event_id"]): row["true_status"]
        for row in labels
    }

    if set(truth_by_key) != set(event_engine_predictions):
        raise ValueError("Labels do not match the engine predictions.")
    if set(truth_by_key) != set(event_baseline_predictions):
        raise ValueError("Labels do not match the baseline predictions.")

    keys = sorted(truth_by_key)
    truth = [truth_by_key[key] for key in keys]
    engine_pred = [event_engine_predictions[key] for key in keys]
    baseline_pred = [event_baseline_predictions[key] for key in keys]

    confusion = {
        actual: {predicted: 0 for predicted in STATUSES}
        for actual in STATUSES
    }
    for actual, predicted in zip(truth, engine_pred):
        confusion[actual][predicted] += 1

    misclassified = [
        {
            "project_id": project_id,
            "event_id": event_id,
            "expected": truth_by_key[(project_id, event_id)],
            "state_engine": event_engine_predictions[(project_id, event_id)],
            "baseline": event_baseline_predictions[(project_id, event_id)],
        }
        for project_id, event_id in keys
        if truth_by_key[(project_id, event_id)]
        != event_engine_predictions[(project_id, event_id)]
    ]

    per_scenario = {}
    for scenario in SCENARIOS:
        scenario_keys = [
            (row["project_id"], row["as_of_event_id"])
            for row in labels
            if row["scenario"] == scenario
        ]
        scenario_truth = [truth_by_key[key] for key in scenario_keys]
        scenario_pred = [event_engine_predictions[key] for key in scenario_keys]
        per_scenario[scenario] = {
            "correct": sum(
                a == b for a, b in zip(scenario_truth, scenario_pred)
            ),
            "total": len(scenario_keys),
        }

    report = {
        "notice": manifest["limitations"],
        "dataset": {
            "synthetic": True,
            "scenarios": len(SCENARIOS),
            "events": len(generated_events),
            "labeled_states": len(labels),
        },
        "state_accuracy": {
            "state_engine": score(truth, engine_pred),
            "latest_explicit_status_baseline": score(truth, baseline_pred),
        },
        "confusion_matrix": confusion,
        "per_scenario": per_scenario,
        "misclassified_states": misclassified,
    }

    results_path.write_text(
        json.dumps(report, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )

    print(json.dumps(report, indent=2, sort_keys=True))
    print(f"\nChallenge dataset: {events_path}")
    print(f"Hand-authored labels: {labels_path}")
    print(f"Benchmark results: {results_path}")


if __name__ == "__main__":
    main()
